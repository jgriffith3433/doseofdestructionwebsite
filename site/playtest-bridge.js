  /** How long the game gets to load and say it's ready before the run ends as an error. */
  var LOAD_MS = 90000;
  /** Query parameters this page reads itself; every other one (room, peer…) is passed on to the game. */
  var OWN = ['playtest', 'seed', 'speed', 'at'];

  var frame = null;
  var run = null; // { id, options, started: ms, status, error, inner: bool }

  function inner() {
    try {
      var w = frame && frame.contentWindow;
      var api = w && w.hawkesPlaytest;
      return api && typeof api.state === 'function' ? api : null;
    } catch (e) {
      return null;
    }
  }

  function gameUrl() {
    var url = new URL('Game/', document.baseURI);
    var q = new URLSearchParams(location.search);
    q.forEach(function (v, k) { if (OWN.indexOf(k) < 0) url.searchParams.append(k, v); });
    return url.toString();
  }

  function openFrame() {
    if (frame) return frame;
    frame = document.createElement('iframe');
    frame.id = 'hawkes-playtest-frame';
    frame.title = 'Dose Of Destruction';
    frame.setAttribute('allow', 'autoplay; fullscreen; gamepad');
    // Opaque brand colour from the first frame so "Loading the game" never shows the landing page underneath.
    frame.style.cssText = 'position:fixed;inset:0;width:100vw;height:100vh;border:0;margin:0;padding:0;z-index:2147483647;background:transparent;display:block;opacity:1';
    var brand = document.createElement('div');
    brand.id = 'hawkes-playtest-brand';
    brand.setAttribute('style', 'position:fixed;inset:0;z-index:2147483646;display:flex;align-items:center;justify-content:center;background:#1c0d06 radial-gradient(ellipse at 50% 45%,#8a3010 0%,#3a1608 45%,#100e0c 80%);color:#fff3df;font:700 clamp(28px,7vw,80px) Oswald,Impact,Arial Narrow,sans-serif;text-transform:uppercase;letter-spacing:.06em;text-align:center');
    brand.innerHTML = 'Dose of <span style="color:#ffd15a;text-shadow:0 3px 0 #5a2410">&nbsp;Destruction</span>';
    document.body.appendChild(brand);
    frame.src = gameUrl();
    document.documentElement.style.overflow = 'hidden';
    document.body.appendChild(frame);
    frame.addEventListener('load', function () { try { frame.focus(); } catch (e) {} });
    return frame;
  }

  function sleep(ms) { return new Promise(function (r) { setTimeout(r, ms); }); }

  function innerReady(api) {
    try { return Boolean(api.state().ready); } catch (e) { return false; }
  }

  function fail(message) {
    if (!run) return;
    run.status = 'error';
    run.error = message;
    run.ended = Date.now();
  }

  function whenBody() {
    if (document.body) return Promise.resolve();
    return new Promise(function (r) { document.addEventListener('DOMContentLoaded', function () { r(); }, { once: true }); });
  }

  var api = {
    version: 1,
    product: 'doseofdestruction',
    scenarios: function () { return SCENARIOS.map(function (s) { return JSON.parse(JSON.stringify(s)); }); },
    start: function (id, options) {
      var opts = JSON.parse(JSON.stringify(options || {}));
      run = { id: String(id), options: opts, started: Date.now(), status: 'running', error: null, ended: 0 };
      var mine = run;
      return whenBody().then(function () {
        openFrame();
        var until = Date.now() + LOAD_MS;
        function wait() {
          if (run !== mine) return Promise.resolve();
          var g = inner();
          if (g && innerReady(g)) {
            mine.inner = true;
            return Promise.resolve(g.start(mine.id, opts)).catch(function (e) { fail('the game\'s start() failed: ' + (e && e.message || e)); });
          }
          if (Date.now() > until) { fail('the game at Game/ didn\'t get ready within ' + LOAD_MS / 1000 + ' s'); return Promise.resolve(); }
          return sleep(250).then(wait);
        }
        return wait();
      });
    },
    state: function () {
      if (!run) return { ready: true, status: 'idle', scene: 'Landing page' };
      if (run.status === 'error') return { ready: true, status: 'error', scene: 'Landing page', note: run.error };
      var g = inner();
      if (run.inner && g) {
        try {
          var s = g.state();
          // The game reloads itself in some scenarios (sound-settings): while it loads again, it's still this run.
          if (!s.ready || s.status === 'idle') return { ready: true, status: 'running', scene: s.scene || 'Loading the game', note: 'the game is loading' };
          return s;
        } catch (e) {}
      }
      return { ready: true, status: 'running', scene: 'Loading the game', progress: 0, note: 'opening Game/' };
    },
    report: function () {
      if (!run) return null;
      var g = inner();
      if (run.status !== 'error' && g) {
        try { var r = g.report(); if (r) return r; } catch (e) {}
      }
      return {
        scenario: run.id,
        outcome: 'error',
        seconds: ((run.ended || Date.now()) - run.started) / 1000,
        metrics: {},
        problems: [{ severity: 'bug', message: run.error || 'the game at Game/ never started the scenario' }],
        log: ['landing page: opened ' + (frame ? frame.src : 'no frame')],
      };
    },
    stop: function () {
      var g = inner();
      if (g && typeof g.stop === 'function') { try { g.stop(); } catch (e) {} }
    },
    input: function (action, down) {
      var g = inner();
      if (g && typeof g.input === 'function') g.input(action, down);
    },
  };
  window.hawkesPlaytest = api;

  // ?playtest=<id> on this page runs it as soon as the page is up (the contract's own way to start one).
  var q = new URLSearchParams(location.search);
  var auto = q.get('playtest');
  if (auto) {
    var num = function (v, d) { var n = Number(v); return v != null && v !== '' && isFinite(n) ? n : d; };
    var at = q.get('at');
    var o = { seed: num(q.get('seed'), 1), speed: num(q.get('speed'), 1) };
    if (at) o.at = at;
    api.start(auto, o);
  }
